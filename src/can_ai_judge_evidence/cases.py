"""Authored synthetic cases. Hidden answers here must never enter model input.

Rates/costs are experimental design assumptions, not clinical estimates.
Each pair shares one world and differs only in its existing monitoring plan.
"""
from dataclasses import dataclass, replace
from fractions import Fraction

from .brief import BriefTarget
from .case_builder import (ChannelBinding, WorldEndpoint, WorldGroup, WorldModel,
                           WorldOutcome, WorldPopulation, build_config)
from .domain import EvaluationConfig, Instrument, Plan


@dataclass(frozen=True)
class CasePair:
    case_id: str
    split: str
    title: str
    narrative: str
    world: WorldModel
    instruments: tuple[Instrument, ...]
    bindings: tuple[ChannelBinding, ...]
    target: BriefTarget
    blind_plan: Plan
    adequate_plan: Plan
    reference_repair: Plan
    budget: int
    deadline_month: int
    # Independent authoring assertions; not inferred from the binding menu.
    offered_pairs: tuple[tuple[str, str], ...]
    expected_feasible_pairs: tuple[tuple[str, str], ...]
    # Less-scaffolded brief: the pathway narrative states which patients are
    # unaffected; the changing group is never named in the public facts.
    open_narrative: str = ''
    open_target: BriefTarget | None = None

    def brief_inputs(self, brief: str) -> tuple[str, BriefTarget]:
        if brief == 'scaffolded':
            return self.narrative, self.target
        if brief == 'open' and self.open_narrative:
            return self.open_narrative, self.open_target or self.target
        raise ValueError('brief must be scaffolded or open (with an authored open narrative)')

    def config(self, variant: str) -> EvaluationConfig:
        if variant not in ('blind', 'adequate'):
            raise ValueError('variant must be blind or adequate')
        return build_config(
            self.world, self.instruments, self.bindings,
            existing_plan=self.blind_plan if variant == 'blind' else self.adequate_plan,
            budget=self.budget, deadline_month=self.deadline_month,
            blind_pairs=((self.blind_plan.channel, self.blind_plan.population),))


def _group(name, size, event, rates, other, other_rate):
    """Two disjoint adverse outcomes plus a residual; source probabilities only."""
    return WorldGroup(name, size, (
        WorldOutcome(event, *rates), WorldOutcome(other, other_rate, other_rate),
        WorldOutcome('neither', *(float(1 - Fraction(str(r)) - Fraction(str(other_rate)))
                                  for r in rates))))


