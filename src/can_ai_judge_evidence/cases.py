def smoke_fixture() -> CasePair:
    """The original mathematical fixture, distinct from development/evaluation."""
    world = WorldModel(
        (_group('seen', 1500, 'missed_event', (0, 0), 'local_event', .02),
         _group('unseen', 8500, 'missed_event', (.005, 70 / 8500), 'local_event', 0)),
        (WorldPopulation('observed', ('seen',)),
         WorldPopulation('non_referred', ('unseen',)),
         WorldPopulation('all_triaged', ('seen', 'unseen'), 'iid_mixture')),
        (WorldEndpoint('missed_event', ('missed_event',)),
         WorldEndpoint('local_event', ('local_event',))), 6)
    pairs = (('audit', 'observed'), ('audit', 'non_referred'), ('audit', 'all_triaged'),
             ('local_records', 'all_triaged'))
    return CasePair(
        'fixture', 'fixture', 'Synthetic transport fixture',
        'This is a mathematical transport fixture with invented inputs.', world,
        (Instrument('audit', 1, 1, 6, 2, 100, 2, 10000),
         Instrument('local_records', 1, 1, 6, 0, 0, 0, 10000)),
        (ChannelBinding('audit', 'missed_event', ('observed', 'non_referred', 'all_triaged')),
         ChannelBinding('local_records', 'local_event', ('all_triaged',))),
        BriefTarget('missed_event', 'non_referred', 'unseen', 'neither'),
        Plan('audit', 'observed', 500, 9), Plan('audit', 'non_referred', 3800, 9),
        Plan('audit', 'non_referred', 3800, 9), 7700, 9, pairs, (),
        'This is a mathematical transport fixture with invented inputs. Seen patients are fully '
        'investigated already, so their outcomes are unaffected.')
